import { aiProvider } from './ai-provider.js'
import { loadConfig } from './config.js'
import { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, PageBreak, BorderStyle, Header, Footer, convertInchesToTwip } from 'docx'
import { writeFileSync } from 'fs'
import { dialog } from 'electron'

const MODEL = 'llama3.2:3b'
const DISCLAIMER = 'DISCLAIMER: This document was generated by AI software for organizational purposes only. It is NOT legal advice. Always consult a licensed attorney for legal guidance. AI-generated content may contain errors or omissions. Verify all facts independently before use in any legal proceeding.'

// Strip markdown formatting artifacts from LLM output
function stripMarkdown(text) {
  if (!text) return ''
  return text
    .replace(/\*\*(.+?)\*\*/g, '$1')       // **bold**
    .replace(/\*(.+?)\*/g, '$1')            // *italic*
    .replace(/__(.+?)__/g, '$1')            // __bold__
    .replace(/_(.+?)_/g, '$1')              // _italic_
    .replace(/^#+\s+/gm, '')               // ## headings
    .replace(/^[-*]\s+/gm, '  - ')         // bullet points → indented dash
    .replace(/^\d+\.\s+/gm, (m) => '  ' + m) // numbered lists → indented
    .replace(/`([^`]+)`/g, '$1')            // `code`
    .replace(/```[\s\S]*?```/g, '')         // code blocks
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1') // [link](url) → link
    .replace(/\n{3,}/g, '\n\n')             // collapse excessive newlines
    .trim()
}

export class OutlineGenerator {
  constructor(db, sendProgress) {
    this.db = db
    this.sendProgress = sendProgress || (() => {})
  }

  async generate() {
    const patterns = this.db.listPatterns()
    const violations = this.db.listViolations()
    const obligations = this.db.listObligations()
    const events = this.db.listTimelineEvents()
    const documents = this.db.listDocuments()

    // Load case info for perspective
    const config = loadConfig() || {}
    this.caseInfo = config.caseInfo || {}
    this.userRole = this.caseInfo.userRole || ''
    this.caseType = this.caseInfo.caseType || 'modification'
    this.isInitial = this.caseType === 'initial'

    const includedViolations = violations.filter((v) => v.included_in_outline)
    const activeViolations = includedViolations.length > 0 ? includedViolations : violations

    this.sendProgress({ stage: 'Generating executive summary...', percent: 10 })

    const summary = await this._generateSummary(activeViolations, patterns, obligations)

    this.sendProgress({ stage: 'Building pattern sections...', percent: 40 })

    const patternSections = []
    for (let i = 0; i < patterns.length; i++) {
      const p = patterns[i]
      const pct = 40 + Math.round((i / patterns.length) * 30)
      this.sendProgress({ stage: `Writing section: ${p.pattern_name}...`, percent: pct })

      const section = await this._generatePatternSection(p, obligations, documents)
      patternSections.push(section)
    }

    this.sendProgress({ stage: 'Generating chronological summary...', percent: 75 })

    // Chronological summary — filter out entries with missing dates or garbled text
    const chronoSummary = events
      .filter((e) => e.event_date && e.event_text && e.event_text !== 'null')
      .slice(0, 50)
      .map((e) => `${e.event_date}: ${e.event_text}`)
      .join('\n')

    // Evidence binder index
    const evidenceIndex = documents.map((d, i) =>
      `Exhibit ${String.fromCharCode(65 + (i % 26))}${i >= 26 ? Math.floor(i / 26) : ''}: ${d.file_name} (${d.classification || 'Unclassified'})`
    ).join('\n')

    // Obligations / Key Issues summary
    const obligationsSummary = obligations.length > 0
      ? obligations.map((o, i) => `${i + 1}. [${o.category || 'General'}] ${o.obligation_text}`).join('\n')
      : this.isInitial ? 'No key issues defined.' : 'No obligations parsed.'

    this.sendProgress({ stage: 'Generating closing summary...', percent: 85 })

    const closingSummary = await this._generateClosingSummary(activeViolations, patterns, obligations, events)

    const outline = {
      disclaimer: DISCLAIMER,
      sections: [
        { title: 'Executive Summary', content: stripMarkdown(summary) },
        { title: this.isInitial ? 'Key Issues' : 'Parsed Obligations from Judgment', content: obligationsSummary },
        ...patternSections.map((s) => ({ title: s.title, content: stripMarkdown(s.content) })),
        { title: 'Chronological Summary of Events', content: chronoSummary || 'No dated events extracted.' },
        { title: 'Evidence Binder Index', content: evidenceIndex || 'No documents uploaded.' },
        { title: 'Summary and Conclusion', content: stripMarkdown(closingSummary) }
      ],
      generatedAt: new Date().toISOString()
    }

    this.sendProgress({ stage: 'Saving outline...', percent: 95 })
    this.db.saveOutline(outline)

    this.sendProgress({ stage: 'Complete', percent: 100 })
    return outline
  }

  async exportDocx(outline) {
    if (!outline) {
      outline = this.db.getOutline()
    }
    if (!outline) throw new Error('No outline to export')

    // Load case type for export
    const config = loadConfig() || {}
    this.caseType = config.caseInfo?.caseType || 'modification'
    this.isInitial = this.caseType === 'initial'

    const children = []

    // ── Title Page ──
    // Spacers for vertical centering
    for (let i = 0; i < 8; i++) {
      children.push(new Paragraph({ children: [new TextRun('')] }))
    }

    const docTitle = this.isInitial ? 'INITIAL CUSTODY CASE PREPARATION OUTLINE' : 'MEDIATION PREPARATION OUTLINE'
    const docSubtitle = this.isInitial
      ? 'Confidential — For Case Preparation Purposes Only'
      : 'Confidential — For Settlement Discussion Purposes Only'

    children.push(
      new Paragraph({
        alignment: AlignmentType.CENTER,
        spacing: { after: 200 },
        children: [new TextRun({ text: docTitle, bold: true, size: 52, font: 'Times New Roman' })]
      }),
      new Paragraph({
        alignment: AlignmentType.CENTER,
        spacing: { after: 100 },
        children: [new TextRun({ text: docSubtitle, size: 24, font: 'Times New Roman', italics: true, color: '555555' })]
      }),
      new Paragraph({
        alignment: AlignmentType.CENTER,
        spacing: { after: 600 },
        children: [new TextRun({ text: `Prepared: ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`, size: 24, font: 'Times New Roman', color: '666666' })]
      }),
      new Paragraph({ children: [new TextRun('')] }),
      // Horizontal rule
      new Paragraph({
        border: { bottom: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' } },
        children: [new TextRun('')]
      }),
      new Paragraph({ spacing: { before: 200 }, children: [new TextRun('')] }),
      // Disclaimer box
      new Paragraph({
        spacing: { before: 200, after: 200 },
        children: [
          new TextRun({ text: 'NOTICE: ', bold: true, size: 18, font: 'Times New Roman', color: '888888' }),
          new TextRun({ text: DISCLAIMER, italics: true, size: 18, font: 'Times New Roman', color: '888888' })
        ]
      }),
      new Paragraph({ children: [new PageBreak()] })
    )

    // ── Table of Contents ──
    children.push(
      new Paragraph({
        heading: HeadingLevel.HEADING_1,
        spacing: { after: 300 },
        children: [new TextRun({ text: 'TABLE OF CONTENTS', bold: true, font: 'Times New Roman', size: 28 })]
      })
    )

    outline.sections.forEach((section, idx) => {
      children.push(
        new Paragraph({
          spacing: { before: 80, after: 80 },
          children: [
            new TextRun({ text: `${idx + 1}.  `, bold: true, font: 'Times New Roman', size: 22 }),
            new TextRun({ text: section.title, font: 'Times New Roman', size: 22 })
          ]
        })
      )
    })

    children.push(new Paragraph({ children: [new PageBreak()] }))

    // ── Sections ──
    for (let sIdx = 0; sIdx < outline.sections.length; sIdx++) {
      const section = outline.sections[sIdx]

      // Section heading
      children.push(
        new Paragraph({
          heading: HeadingLevel.HEADING_1,
          spacing: { before: 240, after: 200 },
          border: { bottom: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' } },
          children: [
            new TextRun({ text: `${sIdx + 1}.  `, bold: true, font: 'Times New Roman', size: 28 }),
            new TextRun({ text: section.title.toUpperCase(), bold: true, font: 'Times New Roman', size: 28 })
          ]
        })
      )

      // Section content
      const paragraphs = (section.content || '').split('\n').filter(Boolean)
      for (const p of paragraphs) {
        const trimmed = p.trim()

        // Detect sub-headers (lines ending with colon or all caps short lines)
        const isSubHeader = (trimmed.endsWith(':') && trimmed.length < 80) ||
          (trimmed === trimmed.toUpperCase() && trimmed.length < 60 && trimmed.length > 3)

        // Detect bullet points
        const isBullet = trimmed.startsWith('- ') || trimmed.startsWith('* ')

        // Detect numbered items (like obligation lists)
        const isNumbered = /^\d+\.\s/.test(trimmed)

        if (isSubHeader) {
          children.push(
            new Paragraph({
              heading: HeadingLevel.HEADING_2,
              spacing: { before: 200, after: 100 },
              children: [new TextRun({ text: trimmed, bold: true, font: 'Times New Roman', size: 24 })]
            })
          )
        } else if (isBullet) {
          children.push(
            new Paragraph({
              indent: { left: convertInchesToTwip(0.5) },
              spacing: { before: 40, after: 40 },
              children: [new TextRun({ text: trimmed, font: 'Times New Roman', size: 22 })]
            })
          )
        } else if (isNumbered) {
          children.push(
            new Paragraph({
              indent: { left: convertInchesToTwip(0.3) },
              spacing: { before: 60, after: 60 },
              children: [new TextRun({ text: trimmed, font: 'Times New Roman', size: 22 })]
            })
          )
        } else {
          children.push(
            new Paragraph({
              spacing: { before: 80, after: 80 },
              children: [new TextRun({ text: trimmed, font: 'Times New Roman', size: 22 })]
            })
          )
        }
      }

      // Section footer
      children.push(
        new Paragraph({
          spacing: { before: 200 },
          alignment: AlignmentType.RIGHT,
          children: [new TextRun({ text: '[AI-Generated Content — Verify All Facts Independently]', italics: true, size: 16, font: 'Times New Roman', color: 'AAAAAA' })]
        }),
        new Paragraph({ children: [new TextRun('')] })
      )

      // Page break between sections (except last)
      if (sIdx < outline.sections.length - 1) {
        children.push(new Paragraph({ children: [new PageBreak()] }))
      }
    }

    const doc = new Document({
      styles: {
        default: {
          document: {
            run: { font: 'Times New Roman', size: 22 }
          }
        }
      },
      sections: [{
        properties: {
          page: {
            margin: {
              top: convertInchesToTwip(1),
              right: convertInchesToTwip(1),
              bottom: convertInchesToTwip(1),
              left: convertInchesToTwip(1)
            }
          }
        },
        headers: {
          default: new Header({
            children: [
              new Paragraph({
                alignment: AlignmentType.RIGHT,
                children: [new TextRun({ text: `${this.isInitial ? 'Initial Custody Case Outline' : 'Mediation Preparation Outline'} — Confidential`, size: 16, font: 'Times New Roman', color: 'AAAAAA', italics: true })]
              })
            ]
          })
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [new TextRun({ text: 'Generated by CustodyCase.ai — Not Legal Advice — Verify All Facts', size: 14, font: 'Times New Roman', color: 'BBBBBB', italics: true })]
              })
            ]
          })
        },
        children
      }]
    })

    const buffer = await Packer.toBuffer(doc)

    const defaultName = this.isInitial ? 'Initial-Custody-Case-Outline.docx' : 'Mediation-Preparation-Outline.docx'
    const result = await dialog.showSaveDialog({
      defaultPath: defaultName,
      filters: [{ name: 'Word Document', extensions: ['docx'] }]
    })

    if (!result.canceled && result.filePath) {
      writeFileSync(result.filePath, buffer)
      return result.filePath
    }

    return null
  }

  _perspectiveNote() {
    if (!this.userRole) return ''
    return `\nIMPORTANT: This document is prepared from the perspective of the ${this.userRole}. Frame all analysis accordingly — the ${this.userRole} is the party presenting this outline. The other party is the one whose violations are being documented.`
  }

  async _generateSummary(violations, patterns, obligations) {
    const context = this.isInitial
      ? `Case Data Summary:
${this.caseInfo.caseName ? `Case: ${this.caseInfo.caseName}` : ''}
${this.caseInfo.caseNumber ? `Case Number: ${this.caseInfo.caseNumber}` : ''}
${this.userRole ? `Prepared by/for: ${this.userRole}` : ''}
- ${obligations.length} key issues identified for initial custody determination
- ${violations.length} pieces of supporting evidence found
- ${patterns.length} key theme(s) identified
- Key themes: ${patterns.map((p) => `${p.pattern_name} (${p.frequency} items, ${p.evidence_strength} evidence)`).join('; ') || 'None'}

Issue categories: ${[...new Set(violations.map((v) => v.category))].filter(Boolean).join(', ') || 'N/A'}`
      : `Case Data Summary:
${this.caseInfo.caseName ? `Case: ${this.caseInfo.caseName}` : ''}
${this.caseInfo.caseNumber ? `Case Number: ${this.caseInfo.caseNumber}` : ''}
${this.userRole ? `Prepared by/for: ${this.userRole}` : ''}
- ${obligations.length} obligations identified from the custody order/judgment
- ${violations.length} potential violations detected
- ${patterns.length} recurring violation pattern(s) identified
- Key patterns: ${patterns.map((p) => `${p.pattern_name} (${p.frequency} occurrences, ${p.evidence_strength} evidence)`).join('; ') || 'None'}

Violation categories: ${[...new Set(violations.map((v) => v.category))].filter(Boolean).join(', ') || 'N/A'}`

    const systemPrompt = this.isInitial
      ? `You are drafting an executive summary for an initial custody case preparation document.
${this._perspectiveNote()}
Write 3-5 paragraphs in a formal, professional tone suitable for presentation to a mediator or family court. Requirements:
- Open with a clear statement of purpose ("This outline presents the key issues and supporting evidence for an initial custody determination...")
- Summarize the key issues identified and evidence gathered
- Briefly characterize the themes and their relevance to the child's best interests
- Note the evidence basis (documents reviewed, timeline events extracted)
- Close with a forward-looking statement about desired custody arrangements and the child's welfare
- Use third-person language throughout ("Petitioner," "Respondent," or "the parties")
- Do NOT use markdown formatting (no **, ##, bullets, etc.)
- Do NOT provide legal advice or conclusions of law
- Maintain neutral, factual, professional tone throughout`
      : `You are drafting an executive summary for a mediation preparation document in a custody case.
${this._perspectiveNote()}
Write 3-5 paragraphs in a formal, professional tone suitable for presentation to a mediator or family court. Requirements:
- Open with a clear statement of purpose ("This outline presents documented instances of...")
- Summarize the total number of obligations, violations, and patterns identified
- Briefly characterize the nature and severity of the violation patterns
- Note the evidence basis (documents reviewed, timeline events extracted)
- Close with a forward-looking statement about resolution goals
- Use third-person language throughout ("Petitioner," "Respondent," or "the parties")
- Do NOT use markdown formatting (no **, ##, bullets, etc.)
- Do NOT provide legal advice or conclusions of law
- Maintain neutral, factual, professional tone throughout`

    try {
      const result = await aiProvider.chat(MODEL, [
        { role: 'system', content: systemPrompt },
        { role: 'user', content: context }
      ])
      return result
    } catch {
      return this.isInitial
        ? `This outline presents ${obligations.length} key issues and ${violations.length} pieces of supporting evidence organized into ${patterns.length} themes for an initial custody determination.`
        : `This outline documents ${violations.length} identified settlement violations grouped into ${patterns.length} recurring patterns, derived from analysis of ${obligations.length} obligations in the governing custody order.`
    }
  }

  async _generatePatternSection(pattern, obligations, documents) {
    const relatedObligations = obligations.filter((o) =>
      o.category && pattern.pattern_type &&
      o.category.toLowerCase().includes(pattern.pattern_type.toLowerCase())
    )

    const context = `Pattern: ${pattern.pattern_name}
Type: ${pattern.pattern_type}
Frequency: ${pattern.frequency} occurrences
Period: ${pattern.first_occurrence || 'Unknown'} to ${pattern.last_occurrence || 'Unknown'}
Description: ${pattern.description}
Evidence Strength: ${pattern.evidence_strength}
Related Violations: ${pattern.violations?.map((v) => `[${v.event_date}] ${v.description}`).join('; ') || 'None listed'}
Related Obligations: ${relatedObligations.map((o) => o.obligation_text).join('; ') || 'None directly matched'}`

    const sectionPrompt = this.isInitial
      ? `You are writing a formal section for an initial custody case preparation document about a key theme supported by evidence.
${this._perspectiveNote()}
Structure the section as follows:
1. Overview — 1-2 sentences describing the theme and its relevance to custody
2. Related Key Issues — reference the specific custody issues this theme addresses
3. Supporting Evidence — describe each piece of evidence with dates and factual details
4. Documentation — cite the types of evidence (documents, communications, records)
5. Relevance to Child's Best Interests — how this theme relates to the child's welfare

Requirements:
- Use formal, professional language suitable for a mediator or judge to review
- Use third-person language ("Petitioner," "Respondent," "the parties")
- Do NOT use markdown formatting (no **, ##, *, bullets, etc.)
- Do NOT provide legal advice, conclusions of law, or recommendations
- Stick strictly to facts presented in the data
- Keep to 3-5 well-structured paragraphs`
      : `You are writing a formal section for a mediation preparation document about a specific pattern of custody order violations.
${this._perspectiveNote()}
Structure the section as follows:
1. Overview — 1-2 sentences describing the pattern
2. Relevant Order Provisions — reference the specific obligations from the judgment that were violated
3. Documented Instances — describe each violation instance with dates and factual details
4. Supporting Evidence — cite the types of evidence (documents, communications, records)
5. Impact — briefly describe the impact of this pattern on the child and co-parenting relationship

Requirements:
- Use formal, professional language suitable for a mediator or judge to review
- Use third-person language ("Petitioner," "Respondent," "the parties")
- Do NOT use markdown formatting (no **, ##, *, bullets, etc.)
- Do NOT provide legal advice, conclusions of law, or recommendations
- Stick strictly to facts presented in the data
- Keep to 3-5 well-structured paragraphs`

    try {
      const content = await aiProvider.chat(MODEL, [
        { role: 'system', content: sectionPrompt },
        { role: 'user', content: context }
      ])
      return { title: pattern.pattern_name, content }
    } catch {
      return {
        title: pattern.pattern_name,
        content: `${pattern.description}\n\nFrequency: ${pattern.frequency} occurrences\nEvidence Strength: ${pattern.evidence_strength}`
      }
    }
  }

  async _generateClosingSummary(violations, patterns, obligations, events) {
    const context = this.isInitial
      ? `Case Summary Data:
${this.userRole ? `Prepared for: ${this.userRole}` : ''}
- ${obligations.length} key issues identified for initial custody
- ${violations.length} pieces of supporting evidence gathered
- ${patterns.length} key themes identified
- ${events.length} timeline events extracted
- Themes: ${patterns.map((p) => `${p.pattern_name} (${p.evidence_strength} evidence)`).join('; ') || 'None'}`
      : `Case Summary Data:
${this.userRole ? `Prepared for: ${this.userRole}` : ''}
- ${obligations.length} obligations from the custody order
- ${violations.length} documented violations
- ${patterns.length} recurring patterns identified
- ${events.length} timeline events extracted
- Patterns: ${patterns.map((p) => `${p.pattern_name} (${p.evidence_strength} evidence)`).join('; ') || 'None'}`

    const closingPrompt = this.isInitial
      ? `You are writing a closing summary for an initial custody case preparation document.
${this._perspectiveNote()}
Write 2-4 paragraphs that:
- Summarize the key issues and supporting evidence gathered
- Highlight the most significant themes relevant to custody determination
- State the proposed custody arrangement and its basis in the child's best interests
- Express the presenting party's goals (stability, appropriate parenting time, child welfare)
- End with a statement about willingness to work toward a fair resolution

Requirements:
- Formal, professional tone suitable for a mediator
- Third-person language
- Do NOT use markdown formatting
- Do NOT provide legal advice
- Focus on facts and the child's best interests`
      : `You are writing a closing summary for a mediation preparation document in a custody case.
${this._perspectiveNote()}
Write 2-4 paragraphs that:
- Summarize the key findings from the analysis
- Highlight the most significant patterns of non-compliance
- State the documented impact on the child and co-parenting relationship
- Express the presenting party's goals for resolution (compliance, stability, best interests of the child)
- End with a statement about willingness to work toward constructive resolution

Requirements:
- Formal, professional tone suitable for a mediator
- Third-person language
- Do NOT use markdown formatting
- Do NOT provide legal advice
- Focus on facts and the child's best interests`

    try {
      const result = await aiProvider.chat(MODEL, [
        { role: 'system', content: closingPrompt },
        { role: 'user', content: context }
      ])
      return result
    } catch {
      return this.isInitial
        ? `This outline presents ${obligations.length} key issues supported by ${violations.length} pieces of evidence organized into ${patterns.length} themes for an initial custody determination. The presenting party seeks a custody arrangement that serves the child's best interests.`
        : `This outline has documented ${violations.length} violations across ${patterns.length} recurring patterns, derived from ${obligations.length} obligations in the governing custody order. The presenting party seeks compliance with all existing court orders in the best interests of the child.`
    }
  }
}
